base = base[base.index("<style>")+7:base.index("/* page */")]
for lang, t in T.items():
    k = 0 if lang == "cs" else 1
    items = [dict(name=n, cat=c, url=u, dates=d, amount=(a[k] if a else ""), text=x[k], when=(w[k] if w else "")) for n,c,u,d,a,x,w in I]
    rep = {kk: v for kk, v in t.items() if isinstance(v, str)}
    rep.update(lang=lang, basecss=base, homehref=("/" if lang=="cs" else "/en/"),
               footlinks="".join(f'<a href="{h}">{l}</a>' for h,l in t["footlinks"]),
               datajson=json.dumps(dict(lang=lang, t=t["t"], cats=t["cats"], items=items), ensure_ascii=False))
    html = TPL
    for kk, v in rep.items():
        html = html.replace("{{"+kk+"}}", v)
    assert "{{" not in html, html[html.index("{{"):html.index("{{")+40]
    out = os.path.join(ROOT, "granty" if lang=="cs" else "en/granty", "index.html")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w", encoding="utf-8").write(html)
    print("wrote", out, len(items))
